import { Platform, Share } from 'react-native';
import { Trip } from '../types';

function money(n: number) {
  return `₹${Math.round(n).toLocaleString('en-IN')}`;
}

export function tripToHtml(trip: Trip): string {
  const total = Object.values(trip.breakdown).reduce((a, b) => a + b, 0);
  const days = trip.itinerary
    .map(
      (d) => `
      <h3>Day ${d.day}: ${escapeHtml(d.title)}</h3>
      <ul>
        ${d.items
          .map(
            (i) =>
              `<li><strong>${escapeHtml(i.time)}</strong> ${escapeHtml(i.title)} — ${escapeHtml(i.detail)} ${
                i.cost ? `(${money(i.cost)})` : ''
              }</li>`
          )
          .join('')}
      </ul>`
    )
    .join('');

  return `<!DOCTYPE html>
<html><head><meta charset="utf-8"/><title>${escapeHtml(trip.destinationName)} itinerary</title>
<style>
  body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;padding:24px;color:#14212B;line-height:1.45}
  h1{color:#0E7C86} .muted{color:#6B7C85} .box{border:1px solid #D5E1E6;border-radius:12px;padding:12px;margin:12px 0}
</style></head>
<body>
  <h1>${escapeHtml(trip.emoji)} ${escapeHtml(trip.destinationName)}</h1>
  <p class="muted">${escapeHtml(trip.summary)}</p>
  <p><strong>${trip.days}</strong> days · <strong>${trip.travelers}</strong> travellers · ${escapeHtml(
    trip.style
  )} · Budget ${money(trip.budget)}</p>
  ${trip.startLocation ? `<p>From: ${escapeHtml(trip.startLocation)}</p>` : ''}
  ${trip.startDate ? `<p>Dates: ${escapeHtml(trip.startDate || '')}${trip.endDate ? ` → ${escapeHtml(trip.endDate)}` : ''}</p>` : ''}
  <div class="box">
    <strong>Estimated budget (approx.)</strong><br/>
    Stay ${money(trip.breakdown.stay)} · Food ${money(trip.breakdown.food)} · Transport ${money(
      trip.breakdown.transport
    )} · Activities ${money(trip.breakdown.activities)} · Misc ${money(trip.breakdown.misc)}<br/>
    <strong>Total ${money(total)}</strong>
  </div>
  ${days}
  <h3>Tips</h3>
  <ul>${trip.tips.map((t) => `<li>${escapeHtml(t)}</li>`).join('')}</ul>
  ${trip.routeUrl ? `<p><a href="${escapeHtml(trip.routeUrl)}">Open route in Google Maps</a></p>` : ''}
  <p class="muted">Generated by TripGenie AI · Prices are estimates</p>
</body></html>`;
}

function escapeHtml(s: string) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Share/print itinerary. Uses expo-print when available; otherwise shares plain text. */
export async function downloadItineraryPdf(trip: Trip): Promise<void> {
  const html = tripToHtml(trip);

  try {
    // Dynamic require so web/typecheck still works if native module is missing at build time.
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const Print = require('expo-print');
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const Sharing = require('expo-sharing');
    const { uri } = await Print.printToFileAsync({ html });
    if (Platform.OS !== 'web' && (await Sharing.isAvailableAsync())) {
      await Sharing.shareAsync(uri, {
        mimeType: 'application/pdf',
        dialogTitle: `${trip.destinationName} itinerary`,
        UTI: 'com.adobe.pdf',
      });
      return;
    }
    await Print.printAsync({ html });
    return;
  } catch {
    // fall through to text share
  }

  const text =
    `${trip.summary}\n\n` +
    trip.itinerary
      .map((d) => `Day ${d.day}: ${d.title}\n` + d.items.map((i) => `  ${i.time} ${i.title}`).join('\n'))
      .join('\n\n');
  await Share.share({ message: text, title: `${trip.destinationName} itinerary` });
}
